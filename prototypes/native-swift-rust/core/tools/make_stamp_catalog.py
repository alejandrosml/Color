"""Writes the Color stamp catalogue from its SVG files.

The stamps are drawn in art/tampons/, one SVG file each (Color 1.1): their
original artwork on a 100 x 100 grid, numbered by their identifier, which
project files store: only ever ADD a file at the end, never renumber or
remove one. This writes src/stamps/catalog.rs, the catalogue compiled into
the core, and, with --preview FILE, an HTML sheet to look at every stamp.

Each <path> of a file is a layer, in its order: its fill and its stroke are
a fixed colour, "none", or the colour the child chooses — data-fill or
data-stroke "couleur" for that colour itself, "sombre" for its shade (7/10 of
each channel), "claire" for its tint (6/10 of the distance to white added);
the files show them with the poppy red #d75e56, which this checks. Path data
uses absolute M, L, C, Q and Z commands only, numbers separated by spaces:
the Flutter interface parses exactly this subset.
"""
import argparse
import pathlib
import re
import xml.etree.ElementTree as ElementTree

P, D, L, NONE = "P", "D", "L", "-"   # chosen colour, its shade, its tint, nothing
ROLES = {"couleur": P, "sombre": D, "claire": L}
SAMPLE = 0xd75e56
SVG = "{http://www.w3.org/2000/svg}"


def paint(element, attribute):
    """The paint of a layer: P, D, L, NONE or a fixed "#rrggbb"."""
    value = element.get(attribute)
    role = element.get(f"data-{attribute}")
    if role is not None:
        assert role in ROLES, f"unknown role {role}"
        assert value == tone(SAMPLE, ROLES[role]), f"{value} is not the {role} of the sample"
        return ROLES[role]
    if value in (None, "none"):
        return NONE
    assert re.fullmatch(r"#[0-9a-f]{6}", value), f"not a colour: {value}"
    return value


def read_stamps(folder):
    """The stamps of the folder, in the order of their numbers."""
    stamps = []
    files = sorted(pathlib.Path(folder).glob("*.svg"))
    for index, file in enumerate(files):
        number, key = file.stem.split("-", 1)
        assert int(number) == index, f"{file.name}: the numbers must go 00, 01, 02…"
        root = ElementTree.parse(file).getroot()
        assert root.get("viewBox") == "0 0 100 100", f"{file.name}: a grid of 100"
        layers = []
        for element in root:
            if element.tag == f"{SVG}title":
                continue
            assert element.tag == f"{SVG}path", f"{file.name}: only paths"
            data = " ".join(element.get("d").split())
            assert re.fullmatch(r"[MLCQZ0-9. -]+", data), f"{file.name}: M, L, C, Q and Z only"
            fill = paint(element, "fill")
            stroke = paint(element, "stroke")
            width = float(element.get("stroke-width", "0")) if stroke != NONE else 0
            layers.append((fill, stroke, width, data))
        stamps.append((key, tuple(layers)))
    return stamps


STAMPS = []


def rust_paint(value):
    return {P: "Primary", D: "Dark", L: "Light", NONE: "None"}.get(value) or f"Fixed(0x{value[1:]})"


def write_rust(path):
    out = ["// SPDX-License-Identifier: MIT",
           "// Generated by tools/make_stamp_catalog.py from art/tampons/: change a",
           "// stamp in its SVG file, not here.",
           "// Identifiers are positions in STAMPS and live in project files:",
           "// append new stamps only.",
           "use super::{Paint::*, Stamp, StampLayer};",
           "",
           "pub(crate) static STAMPS: &[Stamp] = &["]
    for key, layers in STAMPS:
        out.append("    Stamp {")
        out.append(f"        key: \"{key}\",")
        out.append("        layers: &[")
        for fill, stroke, width, data in layers:
            out.append("            StampLayer {")
            out.append(f"                fill: {rust_paint(fill)},")
            out.append(f"                stroke: {rust_paint(stroke)},")
            out.append(f"                width: {float(width)},")
            out.append(f"                path: \"{data}\",")
            out.append("            },")
        out.append("        ],")
        out.append("    },")
    out.append("];")
    pathlib.Path(path).write_text("\n".join(out) + "\n")


def tone(rgb, role):
    r, g, b = (rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255
    if role == D:
        r, g, b = r * 7 // 10, g * 7 // 10, b * 7 // 10
    elif role == L:
        r, g, b = r + (255 - r) * 6 // 10, g + (255 - g) * 6 // 10, b + (255 - b) * 6 // 10
    return f"#{r:02x}{g:02x}{b:02x}"


def svg_paint(value, rgb):
    if value == NONE:
        return "none"
    return tone(rgb, value) if value in (P, D, L) else value


def write_preview(path, colours=(0x477fb2, 0xd75e56, 0xeebf4e, 0x78a66f)):
    cells = []
    for index, (key, layers) in enumerate(STAMPS):
        rgb = colours[index % len(colours)]
        body = "".join(
            f'<path d="{data}" fill="{svg_paint(fill, rgb)}" stroke="{svg_paint(stroke, rgb)}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"/>'
            for fill, stroke, width, data in layers)
        cells.append(f'<figure><svg viewBox="-4 -4 108 108" width="150" height="150">{body}</svg>'
                     f'<figcaption>{index} {key}</figcaption></figure>')
    html = ("<!doctype html><meta charset=utf-8><style>body{margin:16px;background:#fffefa;"
            "font:13px sans-serif;display:grid;grid-template-columns:repeat(6,170px);gap:6px}"
            "figure{margin:0;text-align:center}svg{background:#fff;border:1px solid #d8e2d9;"
            "border-radius:10px}</style>" + "".join(cells))
    pathlib.Path(path).write_text(html)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    root = pathlib.Path(__file__).resolve().parent.parent
    parser.add_argument("--stamps", default=str(root / "art/tampons"))
    parser.add_argument("--output", default=str(root / "src/stamps/catalog.rs"))
    parser.add_argument("--preview")
    arguments = parser.parse_args()
    STAMPS.extend(read_stamps(arguments.stamps))
    keys = [key for key, _ in STAMPS]
    assert len(set(keys)) == len(keys), "duplicate stamp key"
    write_rust(arguments.output)
    if arguments.preview:
        write_preview(arguments.preview)
    print(f"{len(STAMPS)} stamps")
